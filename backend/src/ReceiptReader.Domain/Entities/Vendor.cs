namespace ReceiptReader.Domain.Entities;

/// <summary>
/// A document issuer we have seen before, keyed by Thai tax ID. Approved documents from the same issuer
/// are kept as <see cref="VendorExample"/>s and fed back to the model as few-shot hints,
/// which is how accuracy improves on the "same format again" documents without fine-tuning.
/// Shared by all companies: the layout of a seller's receipt doesn't depend on who bought.
/// </summary>
public class Vendor
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public string TaxId { get; set; } = "";
    public string Name { get; set; } = "";
    public string? Branch { get; set; }
    public int ApprovedReceiptCount { get; set; }
    public DateTimeOffset CreatedAt { get; set; } = DateTimeOffset.UtcNow;
    public DateTimeOffset UpdatedAt { get; set; } = DateTimeOffset.UtcNow;

    public List<VendorExample> Examples { get; set; } = [];
}

public class VendorExample
{
    public Guid Id { get; set; } // generated by EF, see ReceiptLineItem.Id
    public Guid VendorId { get; set; }
    public Guid ReceiptId { get; set; }
    /// <summary>The human-approved extraction, serialized in the same JSON shape the model must produce.</summary>
    public string ApprovedJson { get; set; } = "";
    /// <summary>Pinned examples are always sent first and never rotated out by newer approvals.</summary>
    public bool Pinned { get; set; }
    public DateTimeOffset CreatedAt { get; set; } = DateTimeOffset.UtcNow;
}
