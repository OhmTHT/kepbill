using ReceiptReader.Domain.Enums;

namespace ReceiptReader.Domain.Entities;

/// <summary>
/// One of "our" companies. Its profile fills our side of every document (buyer on purchases,
/// seller on sales), so the model only has to read the counterparty.
/// </summary>
public class Company
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public string Name { get; set; } = "";
    /// <summary>13-digit tax id; empty until the profile is filled in.</summary>
    public string TaxId { get; set; } = "";
    /// <summary>"00000" = สำนักงานใหญ่.</summary>
    public string? Branch { get; set; }
    public string? Address { get; set; }
    /// <summary>จดทะเบียน VAT: input VAT is claimable and sales carry output VAT.</summary>
    public bool VatRegistered { get; set; } = true;
    public DateTimeOffset CreatedAt { get; set; } = DateTimeOffset.UtcNow;
    public DateTimeOffset UpdatedAt { get; set; } = DateTimeOffset.UtcNow;

    public List<Account> Accounts { get; set; } = [];
}

/// <summary>A line of the company's chart of accounts (ผังบัญชี).</summary>
public class Account
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public Guid CompanyId { get; set; }
    public string Code { get; set; } = "";
    public string Name { get; set; } = "";
    public AccountType Type { get; set; }
    public AccountRole Role { get; set; }
    public bool Active { get; set; } = true;
}

/// <summary>
/// A closed accounting month. Open months have no row. Documents whose period is closed, and payments
/// dated in it, can no longer be changed.
/// </summary>
public class ClosedPeriod
{
    public Guid Id { get; set; } // generated by EF
    public Guid CompanyId { get; set; }
    /// <summary>"yyyy-MM".</summary>
    public string Period { get; set; } = "";
    public DateTimeOffset ClosedAt { get; set; }
    public string? ClosedBy { get; set; }
}
